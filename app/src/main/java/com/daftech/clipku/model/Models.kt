package com.daftech.clipku.model

/** Satu kalimat transkrip, dengan batas waktu milidetik. */
data class Sentence(
    val startMs: Long,
    val endMs: Long,
    val text: String
)

/** Satu titik heatmap: fraksi posisi video (0.0-1.0) dan intensitas (0.0-1.0). */
data class HeatPoint(
    val fraction: Double,
    val intensity: Double
)

/** Stream yang bisa dipakai untuk preview / potong. */
data class VideoStream(
    /** URL stream gabungan (video+audio) kalau ada; null kalau hanya adaptive. */
    val progressiveUrl: String?,
    /** URL video-only 720p atau lebih rendah, kalau ada. */
    val videoOnlyUrl: String?,
    /** URL audio-only terbaik, kalau ada. */
    val audioUrl: String?,
    val mimeProgressive: String?,
    /**
     * v1.0.5: deskripsi track audio yang dipilih untuk [audioUrl],
     * mis. "id, original" / "en, dubbed" / "unknown". Dibawa di
     * VideoStream supaya merge Innertube WEB+ANDROID dan merge NewPipe
     * tidak kehilangan info track mana yang kepilih — diagnostik
     * menampilkannya apa adanya. Kosong kalau audioUrl null atau
     * sumbernya tidak memberi info track.
     */
    val audioTrackDescription: String = ""
)

/** Metadata + bahan analisa yang didapat dari Innertube, tanpa mengunduh video. */
data class VideoInfo(
    val videoId: String,
    val title: String,
    val author: String,
    val durationMs: Long,
    val stream: VideoStream,
    val captionTracks: List<CaptionTrack>,
    val heatPoints: List<HeatPoint>,
    /** Chapter dari deskripsi / player, kalau tersedia (best-effort). */
    val chapters: List<String>
)

data class CaptionTrack(
    val baseUrl: String,
    val languageCode: String,
    val name: String,
    val isAutoGenerated: Boolean
)

/** Satu clip highlight hasil scoring. Ini DATA, bukan file video. */
data class Clip(
    val index: Int,
    val startMs: Long,
    val endMs: Long,
    val title: String,
    val reason: String,
    val score: Double,
    /** Transkrip kalimat yang jatuh di dalam clip, untuk narasi. */
    val transcript: String,
    /** Path file hasil Download, null kalau belum diunduh. */
    val savedPath: String? = null,
    /** Teks narasi final, null kalau belum dibuat. */
    val narration: String? = null,
    /**
     * Sumber transkrip yang dipakai narasi ("Transkrip" atau "Whisper"),
     * null kalau narasi belum dibuat. Ini METADATA UI di luar blok
     * narasi — TIDAK PERNAH ikut tersalin tombol Salin, yang hanya
     * menyalin [narration].
     */
    val narrationSource: String? = null,
    val narrationWordCount: Int = 0,
    val narrationError: String? = null,
    val isDownloading: Boolean = false,
    val isGeneratingNarration: Boolean = false,
    /**
     * v1.4.0 (P2-5): durasi AKTUAL file clip hasil download (dari
     * MediaExtractor), bukan durasi yang diminta. Null kalau belum
     * diunduh — UI menampilkan durasi yang diminta saja.
     */
    val actualDurationMs: Long? = null,
    /**
     * v1.4.0 (P1-11): tahap narasi Whisper yang sedang berjalan
     * ("memotong audio clip…", "mengunduh audio clip…",
     * "mentranskrip…", "membuat narasi…"). Null kalau tidak jalan.
     */
    val narrationStage: String? = null,
    /**
     * v1.4.0 (P1-4): peringatan bahasa Whisper, mis. "bahasa
     * terdeteksi en, berbeda dari id". Metadata UI di luar blok
     * narasi — tidak ikut tersalin, tidak disimpan ke History.
     */
    val narrationNote: String? = null
) {
    val durationMs: Long get() = endMs - startMs
}
