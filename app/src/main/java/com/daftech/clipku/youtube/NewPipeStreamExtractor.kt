package com.daftech.clipku.youtube

import com.daftech.clipku.model.CaptionTrack
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.OkHttpClient
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.StreamExtractor
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import org.schabi.newpipe.extractor.stream.VideoStream
import java.util.concurrent.TimeUnit

/**
 * Mesin stream NewPipeExtractor (v1.0.2) — sumber stream PERTAMA.
 *
 * Kenapa NewPipe: Innertube WEB dan ANDROID mengembalikan stream dalam
 * bentuk signatureCipher untuk banyak video (terbukti di video 91 menit
 * tanpa caption, November 2026: audioUrl null dari kedua klien), dan
 * ClipKu v1/v1.0.1 TIDAK men-decipher signature itu. NewPipeExtractor
 * yang men-decipher lewat parser player JS-nya sendiri — ClipKu TIDAK
 * menulis decipher sendiri, itu di luar scope dan rapuh.
 *
 * Yang dipakai dari NewPipe di sini HANYA stream + subtitle:
 *  - audioUrl: stream audio terbaik (diutamakan audio/mp4, sisanya
 *    stream audio pertama yang URL-nya tidak kosong).
 *  - videoUrl: stream video <=720p tertinggi; kalau tidak ada, stream
 *    video terendah di atas 720p (tetap bisa dipakai, hanya lebih besar).
 *    Nilai ini dipakai sebagai videoOnlyUrl, BUKAN progressiveUrl —
 *    stream video NewPipe umumnya video-only, dan menandainya sebagai
 *    progressive akan membuat ClipDownload memotong tanpa audio.
 *  - subtitles: getSubtitlesDefault(), dipetakan ke CaptionTrack.
 *    isAutoGenerated diset false dengan sengaja (NewPipe tidak
 *    mengekspos flag itu lewat getter yang stabil di semua revisi
 *    0.26.x yang dicek) — konsekuensinya hanya urutan preferensi
 *    pemilihan track di fetchTranscriptFromTracks, bukan isi transkrip.
 *
 * Best-effort total: gagal apa pun (NewPipe diblokir, JitPack gagal
 * resolve di Actions, fetchPage gagal) mengembalikan hasil kosong,
 * TIDAK PERNAH melempar ke UI. Innertube tetap fallback.
 * NewPipe.init dipanggil sekali (guard synchronized) karena NewPipe
 * menyimpan Downloader secara global.
 */
data class NewPipeStreamResult(
    val audioUrl: String?,
    val videoUrl: String?,
    val subtitles: List<CaptionTrack>
)

object NewPipeStreamExtractor {

    @Volatile
    private var initialised = false

    suspend fun extract(
        videoId: String,
        http: OkHttpClient = OkHttpClient.Builder()
            .connectTimeout(20, TimeUnit.SECONDS)
            .readTimeout(60, TimeUnit.SECONDS)
            .build()
    ): NewPipeStreamResult = withContext(Dispatchers.IO) {
        try {
            synchronized(this) {
                if (!initialised) {
                    NewPipe.init(OkHttpNewPipeDownloader(http))
                    initialised = true
                }
            }
            val url = "https://www.youtube.com/watch?v=$videoId"
            val extractor: StreamExtractor = ServiceList.YouTube.getStreamExtractor(url)
            extractor.fetchPage()
            val audio = pickAudio(extractor.audioStreams)
            val video = pickVideo(
                (extractor.videoStreams ?: emptyList()) +
                    (extractor.videoOnlyStreams ?: emptyList())
            )
            val subtitles = try {
                (extractor.subtitlesDefault ?: emptyList()).mapNotNull { track ->
                    mapSubtitle(track)
                }
            } catch (e: Exception) {
                emptyList()
            }
            NewPipeStreamResult(audio, video, subtitles)
        } catch (e: Exception) {
            NewPipeStreamResult(null, null, emptyList())
        }
    }

    private fun pickAudio(streams: List<AudioStream>?): String? {
        if (streams.isNullOrEmpty()) return null
        val withUrl = streams.filter { !it.url.isNullOrEmpty() }
        if (withUrl.isEmpty()) return null
        val mp4 = withUrl.firstOrNull { stream ->
            try {
                stream.format?.mimeType?.contains("mp4") == true
            } catch (e: Exception) {
                false
            }
        }
        return (mp4 ?: withUrl.first()).url
    }

    private fun pickVideo(streams: List<VideoStream>): String? {
        val withUrl = streams.filter { !it.url.isNullOrEmpty() }
        if (withUrl.isEmpty()) return null
        val byResolution = withUrl.mapNotNull { stream ->
            val height = parseResolutionHeight(stream.resolution)
            if (height != null) Pair(height, stream.url!!) else null
        }
        if (byResolution.isNotEmpty()) {
            val atOrBelow720 = byResolution.filter { it.first <= 720 }
            if (atOrBelow720.isNotEmpty()) {
                return atOrBelow720.maxByOrNull { it.first }?.second
            }
            return byResolution.minByOrNull { it.first }?.second
        }
        return withUrl.first().url
    }

    /** "720p", "720p60", "1080p" -> 720 / 1080. Null kalau tidak ter-parse. */
    private fun parseResolutionHeight(resolution: String?): Int? {
        if (resolution.isNullOrBlank()) return null
        val digits = resolution.takeWhile { it.isDigit() }
        return digits.toIntOrNull()
    }

    private fun mapSubtitle(track: SubtitlesStream): CaptionTrack? {
        val url = track.url ?: return null
        if (url.isEmpty()) return null
        val language = try {
            track.languageTag ?: ""
        } catch (e: Exception) {
            ""
        }
        return CaptionTrack(
            baseUrl = url,
            languageCode = language,
            name = language.ifEmpty { "subtitle" },
            isAutoGenerated = false
        )
    }
}
